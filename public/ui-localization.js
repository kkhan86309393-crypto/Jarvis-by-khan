function translateAttribute(element, attribute, language) {
  const protectedContent = element.matches?.(ATTRIBUTE_PROTECTION_SELECTOR)
    || element.closest?.(ATTRIBUTE_PROTECTED_CONTENT_SELECTOR);
  if (!protectedContent && element.hasAttribute(attribute)) {
    const current = element.getAttribute(attribute);
    let records = translatedAttributes.get(element);
    if (!records) {
      records = new Map();
      translatedAttributes.set(element, records);
    }
    let record = records.get(attribute);
    if (!record || current !== record.output) {
      record = { source: current, output: current };
      records.set(attribute, record);
    }
    const translated = translateUiText(record.source, language);
    if (translated !== current) element.setAttribute(attribute, translated);
    record.output = translated;
  }
}

function translateAttributeMutation(element, attribute, language) {
  if (TRANSLATABLE_ATTRIBUTES.includes(attribute)) translateAttribute(element, attribute, language);
}

function isProtected(element) {
  return Boolean(element?.closest?.(PROTECTED_CONTENT_SELECTOR));
}

function translateTextNode(node, language) {
  if (!isProtected(node.parentElement)) {
    let record = translatedTextNodes.get(node);
    if (!record || node.nodeValue !== record.output) {
      record = { source: node.nodeValue, output: node.nodeValue };
      translatedTextNodes.set(node, record);
    }
    const translated = translateUiText(record.source, language);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    record.output = translated;
  }
}

function translateElementAttributes(element, language) {
  for (const attribute of TRANSLATABLE_ATTRIBUTES) {
    translateAttribute(element, attribute, language);
  }
  for (const child of element.querySelectorAll?.('*') || []) {
    for (const attribute of TRANSLATABLE_ATTRIBUTES) {
      translateAttribute(child, attribute, language);
    }
  }
}

function visitTextNodes(element, language) {
  if (!element || isProtected(element)) return;
  for (const child of element.childNodes || []) {
    if (child.nodeType === 3) translateTextNode(child, language);
    else if (child.nodeType === 1) visitTextNodes(child, language);
  }
}

export function applyUiLanguage(root, language = 'en') {
  const selectedLanguage = normalizeUiLanguage(language);
  const document = root.ownerDocument || root;
  if (document.title) document.title = translateUiText(document.title, selectedLanguage);
  if (document.documentElement && document.documentElement.lang !== selectedLanguage) {
    document.documentElement.lang = selectedLanguage;
  }
  visitTextNodes(root, selectedLanguage);
  translateElementAttributes(root, selectedLanguage);
  return selectedLanguage;
}

export function observeUiLanguage(document, getLanguage) {
  const Observer = document.defaultView?.MutationObserver || globalThis.MutationObserver;
  if (!Observer || !document.body) return () => {};
  const observer = new Observer((mutations) => {
    const language = normalizeUiLanguage(getLanguage());
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        translateTextNode(mutation.target, language);
      } else if (mutation.type === 'attributes') {
        translateAttributeMutation(mutation.target, mutation.attributeName, language);
      } else {
        for (const node of mutation.addedNodes) {
          if (node.nodeType === 3) translateTextNode(node, language);
          else if (node.nodeType === 1) {
            visitTextNodes(node, language);
            translateElementAttributes(node, language);
          }
        }
      }
    }
  });
  observer.observe(document.body, {
    attributes: true,
    attributeFilter: TRANSLATABLE_ATTRIBUTES,
    childList: true,
    characterData: true,
    subtree: true,
  });
  return () => observer.disconnect();
}
