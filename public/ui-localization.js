function preserveWhitespace(source, replacement) {
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  return `${leading}${replacement}${trailing}`;
}

export function normalizeUiLanguage(language) {
  return language === 'hi' ? 'hi' : 'en';
}

export function getUiLanguagePreference(preferences) {
  return normalizeUiLanguage(preferences?.language);
}

export function translateUiText(text, language = 'en') {
  const selectedLanguage = normalizeUiLanguage(language);
  const trimmed = String(text).trim();
  if (!trimmed) return text;
  if (selectedLanguage === 'hi') {
    const translated = ENGLISH_TO_HINDI[trimmed];
    if (translated) return preserveWhitespace(String(text), translated);
    const dynamic = translateDynamicUiText(trimmed, 'hi');
    return dynamic ? preserveWhitespace(String(text), dynamic) : text;
  }
  const translated = HINDI_TO_ENGLISH.get(trimmed) || translateDynamicUiText(trimmed, 'en');
  return translated ? preserveWhitespace(String(text), translated) : text;
}

